export type AIModeKey = keyof typeof AI_MODES

const FORBIDDEN_KEYWORDS = [
  "взлом",
  "хакинг",
  "хакнуть",
  "бомба",
  "террор",
  "террорист",
  "наркотик",
  "наркотики",
  "оружие",
  "самоубийство",
  "суицид",
  "казино",
  "ставки",
  "букмекер",
  "обойти защиту",
  "как украсть",
]

export function isMessageSafe(text: string): boolean {
  const lower = text.toLowerCase()
  return !FORBIDDEN_KEYWORDS.some((keyword) => lower.includes(keyword))
}

export function getModeConfig(mode: AIModeKey = "default") {
  return AI_MODES[mode] || AI_MODES.default
}
