export type AIModeKey = keyof typeof AI_MODES

export const AI_MODE_KEYS = Object.keys(AI_MODES) as AIModeKey[]

const LANGUAGE_RULES: Record<AppLanguage, string> = {
  ru: "Отвечай на русском языке, если пользователь явно не попросил другой язык.",
  kk: "Отвечай на казахском языке, если пользователь явно не попросил другой язык. Используй принятую в школах Казахстана терминологию.",
  en: "Answer in English unless the user explicitly asks for another language.",
}

export function getModeConfig(mode: AIModeKey = "default") {
  return AI_MODES[mode] ?? AI_MODES.default
}

export function buildSystemPrompt(mode: AIModeKey, language: AppLanguage = "ru") {
  const config = getModeConfig(mode)
  return [config.systemPrompt, SHARED_RULES, LANGUAGE_RULES[language] ?? LANGUAGE_RULES.ru].join("\n\n")
}
